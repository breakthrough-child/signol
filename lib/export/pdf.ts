import PDFDocument from "pdfkit";
import { CHOICE_LABELS, type DecisionLog } from "@/lib/decision";
import type { ScriptDoc } from "@/lib/db-types";
import { TYPE_LABELS } from "@/lib/types";

/** pdfkit's built-in fonts cover WinAnsi only; map or replace anything outside it (e.g. the naira sign). */
export function pdfSafe(s: string): string {
  return s
    .replace(/₦/g, "NGN ")
    .replace(/[ -​ ]/g, " ")
    .replace(/[^\x09\x0A\x0D\x20-\x7E -ÿ‘’“”–—•…]/g, "?");
}

const INK = "#16181D";
const MUTED = "#5B6170";
const ACCENT = "#C2410C";

class Writer {
  doc: PDFKit.PDFDocument;
  constructor() {
    this.doc = new PDFDocument({ size: "A4", margin: 56, info: { Title: "signol", Producer: "signol" } });
  }
  h1(t: string) {
    this.doc.font("Helvetica-Bold").fontSize(20).fillColor(INK).text(pdfSafe(t)).moveDown(0.4);
  }
  h2(t: string) {
    this.doc.moveDown(0.6).font("Helvetica-Bold").fontSize(13).fillColor(ACCENT).text(pdfSafe(t)).moveDown(0.25);
  }
  h3(t: string) {
    this.doc.moveDown(0.3).font("Helvetica-Bold").fontSize(11).fillColor(INK).text(pdfSafe(t)).moveDown(0.15);
  }
  p(t: string, muted = false) {
    this.doc.font("Helvetica").fontSize(10.5).fillColor(muted ? MUTED : INK).text(pdfSafe(t), { lineGap: 2 }).moveDown(0.3);
  }
  quote(t: string, by?: string) {
    this.doc.font("Helvetica-Oblique").fontSize(10.5).fillColor(INK).text(pdfSafe(`“${t}”`), { indent: 12, lineGap: 2 });
    if (by) this.doc.font("Helvetica").fontSize(9).fillColor(MUTED).text(pdfSafe(by), { indent: 12 });
    this.doc.moveDown(0.3);
  }
  bullet(t: string) {
    this.doc.font("Helvetica").fontSize(10.5).fillColor(INK).text(pdfSafe(`•  ${t}`), { indent: 8, lineGap: 2 });
  }
  gap() {
    this.doc.moveDown(0.4);
  }
  async finish(): Promise<Buffer> {
    const chunks: Buffer[] = [];
    this.doc.on("data", (c: Buffer) => chunks.push(c));
    const done = new Promise<void>((r) => this.doc.on("end", () => r()));
    this.doc.end();
    await done;
    return Buffer.concat(chunks);
  }
}

const fmt = (iso: string) => new Date(iso).toISOString().replace("T", " ").slice(0, 16) + " UTC";

export async function decisionLogToPdf(log: DecisionLog): Promise<Buffer> {
  const w = new Writer();
  w.h1(`Decision log: ${log.project.name}`);
  w.p(`Decision: ${CHOICE_LABELS[log.choice]}  ·  ${fmt(log.decidedAt)}`);
  w.h2("Hypothesis");
  w.p(log.project.hypothesis);
  w.p(`Target customer: ${log.project.target_customer}`, true);
  w.h2("Pre-committed prediction (Checkpoint 1)");
  w.p(`Before any analysis you predicted ${log.prediction.supporters} of ${log.analysis.interviews} interviewees would support the hypothesis, with ${log.prediction.confidence}% confidence.`);
  w.h2("What the evidence shows");
  w.p(log.evidence.headline);
  const s = log.evidence.score;
  w.bullet(`Verified statements: ${s.verifiedCount} (${log.analysis.quotesVerified}/${log.analysis.quotesTotal} quotes verified against transcripts)`);
  w.bullet(`Strong evidence: ${s.strongFor} for · ${s.strongAgainst} against`);
  w.bullet(`Answers tainted by leading questions: ${s.tainted}`);
  w.bullet(`Interviewees with strong supporting evidence: ${s.supporters} of ${s.interviewCount}`);
  if (log.analysis.source === "cached") w.bullet("Analysis source: cached demo analysis (not a live model run)");
  w.h3("Strongest evidence for");
  if (!log.topFor.length) w.p("None found.", true);
  for (const e of log.topFor) {
    w.quote(e.quote, `${e.interview} · ${TYPE_LABELS[e.type]} · ${e.strength}${e.tainted ? " · tainted" : ""}`);
    w.p(e.why, true);
  }
  w.h3("Strongest evidence against");
  if (!log.topAgainst.length) w.p("None found.", true);
  for (const e of log.topAgainst) {
    w.quote(e.quote, `${e.interview} · ${TYPE_LABELS[e.type]} · ${e.strength}${e.tainted ? " · tainted" : ""}`);
    w.p(e.why, true);
  }
  if (log.themes.length) {
    w.h3("Themes");
    for (const t of log.themes) w.bullet(`${t.title}: ${t.summary}`);
  }
  if (log.openQuestions.length) {
    w.h3("Open questions");
    for (const q of log.openQuestions) w.bullet(q);
  }
  w.h2("Your responses to the evidence (Checkpoint 2)");
  if (!log.responses.length) w.p("No responses were required for this decision.", true);
  for (const r of log.responses) {
    w.p(`${r.side === "against" ? "Counter-evidence" : "Supporting evidence"} (${r.interview})`, true);
    w.quote(r.quote);
    w.p(`Your response: ${r.response}`);
  }
  w.h2("Calibration");
  w.p(log.calibration.reflection);
  w.gap();
  w.p("Generated by signol. signol never makes the decision; the founder does.", true);
  return w.finish();
}

export async function scriptToPdf(projectName: string, hypothesis: string, script: ScriptDoc): Promise<Buffer> {
  const w = new Writer();
  w.h1(`Next interview script: ${projectName}`);
  w.p(`Hypothesis: ${hypothesis}`, true);
  w.p("Ask about specific past behavior and real events. Do not pitch, and do not ask about the future.", true);
  w.h2("Rewritten (were leading)");
  if (!script.rewritten.length) w.p("No leading questions were found.", true);
  script.rewritten.forEach((r, i) => {
    w.p(`${i + 1}. ${r.rewrite}`);
    w.p(`Was: “${r.original}”. ${r.why}`, true);
  });
  w.h2("Keep (neutral already)");
  script.kept.forEach((k, i) => w.p(`${i + 1}. ${k.question}`));
  w.h2("New questions");
  script.added.forEach((a, i) => {
    w.p(`${i + 1}. ${a.question}`);
    w.p(`Targets: ${a.targets}`, true);
  });
  return w.finish();
}

export function scriptToMarkdown(projectName: string, hypothesis: string, script: ScriptDoc): string {
  const L: string[] = [`# Next interview script: ${projectName}`, "", `**Hypothesis:** ${hypothesis}`, "", "> Ask about specific past behavior and real events. Do not pitch, and do not ask about the future.", ""];
  L.push("## Rewritten (these were leading)", "");
  if (!script.rewritten.length) L.push("_No leading questions were found._", "");
  script.rewritten.forEach((r, i) => L.push(`${i + 1}. ${r.rewrite}`, `   - Was: “${r.original}” — ${r.why}`));
  L.push("", "## Keep (neutral already)", "");
  script.kept.forEach((k, i) => L.push(`${i + 1}. ${k.question}`));
  L.push("", "## New questions", "");
  script.added.forEach((a, i) => L.push(`${i + 1}. ${a.question}`, `   - Targets: ${a.targets}`));
  L.push("", "---", "", "_Generated by signol._");
  return L.join("\n");
}
